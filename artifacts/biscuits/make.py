"""Assemble the three author scripts: common.py + <name>_part.py ->
<name>_author.py. Bundle and preflight are run as separate commands."""
from pathlib import Path

here = Path(__file__).parent
common = (here / "common.py").read_text(encoding="utf-8")
for name in ("jammie", "wafer", "custard", "feet_test"):
    part = (here / (name + "_part.py")).read_text(encoding="utf-8")
    doc = '"""Dangly biscuit ornament: %s. GENERATED by make.py from\ncommon.py + %s_part.py - edit those, not this file."""\n' % (name, name)
    out = here / (name + "_author.py")
    out.write_text(doc + common.rstrip("\n") + "\n" + part,
                   encoding="utf-8", newline="\n")
    print("wrote", out.name)
